// Synthetic, cold-process check and staged-lint measurements. All writes stay
// under os.tmpdir(). An optional baseline CLI must produce identical results.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const [sizesArg = "1000,5000,10000", runsArg = "3", baselineArg] = process.argv.slice(2);
const sizes = sizesArg.split(",").map(Number);
const runs = Number(runsArg);
assert(
  sizes.every((size) => Number.isSafeInteger(size) && size > 0),
  "pages must be positive integers",
);
assert(Number.isSafeInteger(runs) && runs > 0, "runs must be a positive integer");
const cli = fileURLToPath(new URL("../packages/cli/dist/main.js", import.meta.url));
const binaries = baselineArg === undefined ? [cli] : [resolve(baselineArg), cli];
const commands = [["check"], ["check", "--write"], ["lint", "--staged"]];
const median = (values: number[]): number =>
  [...values].sort((a, b) => a - b)[Math.floor(values.length / 2)] ?? 0;

function run(root: string, binary: string, args: string[]) {
  const start = performance.now();
  const result = spawnSync(process.execPath, [binary, ...args, "--root", root, "--all"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  const ms = performance.now() - start;
  assert.equal(result.status, 0, result.stdout + result.stderr);
  assert.equal(result.stderr, "");
  const envelope = JSON.parse(result.stdout) as { data: { generated?: { files: string[] } } };
  const artifacts = Object.fromEntries(
    (envelope.data.generated?.files ?? []).map((path) => [
      path,
      createHash("sha256")
        .update(readFileSync(join(root, path)))
        .digest("hex"),
    ]),
  );
  return { ms, stdout: result.stdout, artifacts };
}

for (const count of sizes) {
  const root = mkdtempSync(join(tmpdir(), "ww-benchmark-"));
  try {
    for (const dir of ["config", "wiki", "empty-hooks"]) mkdirSync(join(root, dir));
    writeFileSync(
      join(root, "config/constitution.json"),
      JSON.stringify({
        schema: "wikiwright/constitution",
        schema_version: 3,
        vocabularies: { tags: { mode: "registered", entries: {} } },
        types: { note: { extends: "concept", description: "A synthetic benchmark note." } },
      }),
    );
    writeFileSync(join(root, "config/engine.json"), JSON.stringify({ content_roots: ["wiki"] }));
    const page = (i: number): string => {
      const links = [1, 2, 3].map((n) => `[[Note ${(i + n) % count}]]`).join(" and ");
      return `---\ntype: note\ntitle: Note ${i}\ndescription: A synthetic benchmark note.\ntags: []\n---\n\n# Note ${i}\n\nSee ${links}.\n`;
    };
    for (let i = 0; i < count; i++) writeFileSync(join(root, "wiki", `Note ${i}.md`), page(i));
    const git = (...args: string[]): void => {
      execFileSync("git", args, { cwd: root, stdio: "pipe" });
    };
    git("init", "-q");
    git("config", "core.hooksPath", join(root, "empty-hooks"));
    git("add", "config", "wiki");
    git(
      "-c",
      "user.name=Benchmark",
      "-c",
      "user.email=benchmark@example.com",
      "-c",
      "commit.gpgsign=false",
      "commit",
      "-qm",
      "test: synthetic baseline",
    );
    writeFileSync(join(root, "wiki/Note 0.md"), `${page(0)}\nA staged edit.\n`);
    git("add", "wiki/Note 0.md");
    // Initialize generated files and verify both renderers before timing.
    const initial = run(root, binaries[0] ?? cli, ["check", "--write"]);
    for (const binary of binaries.slice(1)) {
      const result = run(root, binary, ["check", "--write"]);
      assert.equal(result.stdout, initial.stdout, "initial write envelopes differ");
      assert.deepEqual(result.artifacts, initial.artifacts, "initial generated bytes differ");
    }
    for (const args of commands) {
      const samples = binaries.map(() => [] as number[]);
      let expected: ReturnType<typeof run> | undefined;
      for (let round = 0; round < runs; round++) {
        const order = binaries.map((_, i) => i);
        if (round % 2 === 1) order.reverse();
        for (const i of order) {
          const result = run(root, binaries[i] ?? cli, args);
          if (expected !== undefined) {
            assert.equal(result.stdout, expected.stdout, "complete envelopes differ");
            assert.deepEqual(result.artifacts, expected.artifacts, "generated bytes differ");
          }
          expected = result;
          samples[i]?.push(result.ms);
        }
      }
      console.log(
        JSON.stringify({
          runtime:
            process.versions["bun"] === undefined
              ? `Node ${process.version}`
              : `Bun ${process.versions["bun"]}`,
          pages: count,
          command: args.join(" "),
          runs,
          results: binaries.map((binary, i) => ({
            binary,
            median_ms: Math.round(median(samples[i] ?? [])),
            samples_ms: samples[i]?.map(Math.round),
          })),
          identical: true,
        }),
      );
    }
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}
